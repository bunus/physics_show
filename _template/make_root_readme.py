#!/usr/bin/env python3
# 生成根目录 README.md
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = json.load(open(os.path.join(ROOT, '_template', 'manifest.json'), encoding='utf-8'))

total = sum(len(b['chapters']) for b in data['books'])
lines = []
lines.append('# 高中物理动态演示 · Physics Showit\n')
lines.append('一套按人教版（2019）教材顺序组织的高中物理动态教学网页：6 册、%d 章、%d 个交互情境，面向四川成都高中物理课堂。' % (total, total * 5))
lines.append('每章一个可独立打开的单文件页面，用「左栏情境 + 中栏画布 + 右栏要点 + 底部图鉴」的结构，把物理过程、公式与实时数据联动起来。\n')
lines.append('打开根目录的 [index.html](index.html) 进入总览，选择章节；也可以直接双击任意章节目录下的 index.html。\n')
lines.append('> 无需联网、无需安装依赖、无需本地服务器。现代浏览器（Chrome / Edge / Firefox / Safari）直接打开即可。\n')
lines.append('![高中物理动态演示总览](preview.png)\n')
lines.append('---\n')
lines.append('## 快速开始\n')
lines.append('1. 双击根目录 index.html，按教材分册浏览 %d 章。' % total)
lines.append('2. 点击缩略图或「快速预览」在本页内嵌查看演示；「打开页面」在新窗口打开。')
lines.append('3. 在章节页左栏切换情境，拖动画布端点或调节滑块、开关。')
lines.append('4. 顶部「重置本节」恢复当前情境，「全屏」用于课堂投屏；带播放键的情境可播放 / 暂停物理过程。')
lines.append('5. 键盘 ← / → 切换情境，空格播放或暂停。\n')
lines.append('### 课堂使用建议\n')
lines.append('- **新授课**：先用第一个情境建立直观，再切到规律与公式情境，最后用应用情境收束。')
lines.append('- **复习课**：直接点底部「情境图鉴」跳转到目标情境，配合右栏实时数据讲解。')
lines.append('- **实验课**：用滑块改变条件，让学生先预测、再看数据是否与预测一致。')
lines.append('- **投屏**：进入全屏，隐藏浏览器地址栏；画布与数据会随窗口自适应。\n')
lines.append('---\n')
lines.append('## 教材结构\n')
for book in data['books']:
    lines.append('### %s\n' % book['name'])
    lines.append('| 页面 | 内容 |')
    lines.append('| --- | --- |')
    for ch in book['chapters']:
        lines.append('| [%s](%s/index.html) | %s |' % (ch['title'], ch['dir'], ch['desc']))
    lines.append('')
lines.append('---\n')
lines.append('## 目录结构\n')
lines.append('```')
lines.append('物理演示/')
lines.append('├─ index.html                总览页（由 _template/portal.py 生成）')
lines.append('├─ <章>/index.html           单文件章节页（构建产物）')
lines.append('├─ <章>/preview.png          章节预览图')
lines.append('├─ <章>/README.md            章节说明')
lines.append('└─ _template/                构建源')
lines.append('   ├─ template.html         布局 / 样式 / Canvas 引擎')
lines.append('   ├─ src/<章>/modules.js   本章 5 个情境')
lines.append('   ├─ src/<章>/meta.json    标题与文案')
lines.append('   ├─ build.py / portal.py / make_readmes.py / make_previews.py / qa.py')
lines.append('   └─ manifest.json         教材目录')
lines.append('```\n')
lines.append('---\n')
lines.append('## 构建与维护\n')
lines.append('```bash')
lines.append('python3 _template/qa.py            # 构建全部章节 + 运行时自检')
lines.append('python3 _template/make_readmes.py  # 生成各章 README')
lines.append('python3 _template/make_previews.py # 生成各章 preview.png（Windows Edge）')
lines.append('python3 _template/portal.py        # 生成根目录总览页')
lines.append('```\n')
lines.append('只改某一章时：\n')
lines.append('```bash')
lines.append('python3 _template/build.py 抛体运动')
lines.append('```\n')
lines.append('---\n')
lines.append('## 说明\n')
lines.append('- 单文件交付：HTML / CSS / JavaScript 与全部图形均内联，可单独复制到任意目录双击打开。')
lines.append('- 所有画面由 Canvas 实时绘制，无外部图片、字体或第三方库。')
lines.append('- 物理量取 g = 9.8 或 10 m/s² 时会在各章公式与读数中统一说明。')
lines.append('- 拖动端点被限制在当前视野内；刷新后回到第一个情境。\n')
lines.append('## 许可\n')
lines.append('MIT License，可自由用于课堂教学与校本教研。')
open(os.path.join(ROOT, 'README.md'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('readme written', total)
